def card_caption(photo, index: int, total: int, owned: bool) -> str:
    """Подпись карточки в каталоге."""
    desc = photo["description"] or ""
    desc_block = f"\n{desc}\n" if desc else ""
    owned_line = "\n✅ <i>Уже в вашей коллекции</i>" if owned else ""
    return (
        f"<b>{index + 1}/{total} · «{photo['title']}»</b>\n"
        f"{desc_block}\n"
        f"<blockquote>💫 Цена: <b>{photo['price_stars']} ⭐</b>{owned_line}</blockquote>"
    )


def plural(n: int, forms=("кадр", "кадра", "кадров")) -> str:
    n = abs(n) % 100
    if 11 <= n <= 19:
        return forms[2]
    n %= 10
    if n == 1:
        return forms[0]
    if 2 <= n <= 4:
        return forms[1]
    return forms[2]


